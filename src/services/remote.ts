/**
 * 远端存储端口（Phase 9B）：把「同步这件事」和「用哪个后端」分开。
 *
 * 这一层存在的理由与 `services/storage.ts` 同源：**换掉后端时不该动同步逻辑**。
 * 同步引擎（`services/cloudSync.ts`）只认下面的接口，一行 CloudBase 的代码都不认识；
 * 云端实现（`services/cloudbase.ts`）也只知道怎么读写文档，不知道什么叫「最后写入胜出」。
 * 于是同步引擎可以用一个内存实现跑完整的自检（含断网、出错、并发），
 * 而真机上的后端差异被关在适配器里——这是 9B 唯一需要「对着真环境才能验证」的部分。
 *
 * **粒度：一个存储键 = 一份文档**。与 Phase 9A 的同步单元完全一致（那边也是按键盘
 * 重读、按键盘替换），所以同设备同步与跨设备同步用的是同一套「整份数组」语义，
 * 不存在「本地按份、云端按字段」两套规则打架。
 */

/** 远端的一份「键 → 内容」 */
export interface RemoteDoc {
  /** 本机存储键名（`teacherdesk:students`）——远端文档的身份就是它，不另起编号 */
  key: string
  /** 该键的整份内容，与 localStorage 里那份同形（一个数组） */
  payload: unknown[]
  /**
   * 这份内容**在写入方那边**的时刻（毫秒），最后写入胜出靠它比大小。
   * 由写入方产生，所以两台设备的系统时间差会直接变成胜负偏差——这是拍板口径
   * 「最后写入胜出」的固有边界，写进开发手册，不在这里偷偷加逻辑去掩饰。
   */
  updatedAt: number
}

/**
 * 远端端口。三个方法都可能因网络 / 鉴权 / 权限失败而抛错，
 * **调用方负责决定「失败之后怎么办」**（同步引擎的做法是：保持本地不动，等下次重试——
 * 本地磁盘本身就是队列，不需要另建一套待发队列）。
 */
export interface RemotePort {
  /** 拉取全部文档（键由调用方按本机注册表对照，这里不做筛选） */
  pull(): Promise<RemoteDoc[]>
  /** 按键整份覆盖写入 */
  push(doc: RemoteDoc): Promise<void>
  /**
   * 删除某个键。**当前没有任何调用方**——同步引擎不传播删除（见开发手册「无删除传播、
   * 无墓碑」那条边界：本地清空后重载会重新播种，而把「云端缺失」当成删除指令的话，
   * 一次误删会顺着所有设备把数据清干净）。
   *
   * 保留它是为了将来真要加删除传播时接口先在这里：云端实现已经写好，补上引擎侧的判定
   * 即可，不必再动端口形状。别被它的存在误导成「删除已经会同步出去」。
   */
  remove(key: string): Promise<void>
}
